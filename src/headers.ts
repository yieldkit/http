import type { HttpClientResponse } from 'effect/http';

import { Clock, Duration, Effect, Option, Result } from 'effect';
import { Headers } from 'effect/http';

import { readSharedBodyPrefix } from './body.ts';
import { HttpRateLimitedError } from './errors.ts';
import { DEFAULT_EDGE_403_RETRY_AFTER_SECONDS } from './policy.ts';

/**
 * Bytes of a 403 body inspected for a CDN or WAF block page. Block pages put their markers near the
 * top, so the rest of the body is never read.
 */
const EDGE_BLOCK_SNIFF_BYTES = 64 * 1024;

/**
 * Markers that only CDN, WAF and anti-bot block or challenge pages carry: Cloudflare challenge and
 * error pages (`cf-chl`, `Attention Required! | Cloudflare`, `Just a moment...`, the Ray ID
 * footer), Akamai's `Reference #` denial and `errors.edgesuite.net`, AWS WAF and CloudFront block
 * pages, Imperva/Incapsula, Sucuri, DDoS-Guard, PerimeterX, DataDome, and CAPTCHA widgets. A plain
 * `403 Forbidden` or permission page matches none of them.
 */
const HTML_EDGE_BLOCK_RE =
  /cf[-_]chl|challenge-platform|attention required! \| cloudflare|<title>just a moment\.\.\.<\/title>|cloudflare ray id|access denied[\s\S]{0,400}reference #|errors\.edgesuite\.net|generated by cloudfront|aws waf|_incapsula_resource|incapsula incident|sucuri website firewall|ddos-guard|px-captcha|perimeterx|captcha-delivery\.com|datadome|g-recaptcha|h-captcha|hcaptcha\.com|cf-turnstile/i;

/**
 * Response headers that CDNs and WAFs set only on a page they generated to block or challenge the
 * client: Cloudflare's `cf-mitigated`, AWS WAF's `x-amzn-waf-action` and DataDome's `x-datadome`.
 */
const EDGE_BLOCK_HEADERS: ReadonlyArray<string> = [
  'cf-mitigated',
  'x-amzn-waf-action',
  'x-datadome',
];

/**
 * Largest delay, in seconds, a rate-limit header can produce (about 68 years). A larger or
 * unbounded value is cut to it, so the delay stays finite and far above any inline retry limit.
 */
export const MAX_RATE_LIMIT_DELAY_SECONDS = 2 ** 31 - 1;

/**
 * Cuts a delay in seconds to a whole, finite number between 0 and `MAX_RATE_LIMIT_DELAY_SECONDS`.
 * `NaN` gives `null`.
 */
const clampDelaySeconds = (seconds: number): number | null => {
  if (Number.isNaN(seconds)) {
    return null;
  }

  return Math.min(MAX_RATE_LIMIT_DELAY_SECONDS, Math.max(0, Math.ceil(seconds)));
};

/**
 * Matches identical integer values joined by a transport when a header is repeated.
 */
const REPEATED_INTEGER_HEADER_RE = /^(\d+)(?:\s*,\s*\1)+$/u;

/**
 * Returns the first non-empty trimmed header value matching any of `names`.
 */
const getHeaderValue = (headers: Headers.Headers, names: ReadonlyArray<string>): string | null => {
  for (const name of names) {
    const value = Headers.get(headers, name);
    if (Option.isSome(value)) {
      const trimmed = value.value.trim();
      if (trimmed.length > 0) {
        return trimmed;
      }
    }
  }

  return null;
};

/**
 * Parses an RFC 9110 `Retry-After` header (delta-seconds or HTTP-date) into whole delay seconds,
 * cut to `MAX_RATE_LIMIT_DELAY_SECONDS`. Identical repeated delta-seconds count as one value.
 * Missing or invalid values return null.
 */
export const parseRetryAfterSeconds = (headers: Headers.Headers, nowMs: number): number | null => {
  const raw = getHeaderValue(headers, ['retry-after']);
  if (raw === null) {
    return null;
  }

  const parsed = Headers.parseRetryAfter(REPEATED_INTEGER_HEADER_RE.exec(raw)?.[1] ?? raw);
  if (Result.isFailure(parsed)) {
    return null;
  }

  const delay = Headers.retryAfterDelay(parsed.success, nowMs);
  return clampDelaySeconds(Duration.toMillis(delay) / 1000);
};

/**
 * Parses `x-ratelimit-reset-after` or `x-ratelimit-reset` headers into remaining delay seconds, cut
 * to `MAX_RATE_LIMIT_DELAY_SECONDS`.
 */
export const parseRateLimitResetSeconds = (
  headers: Headers.Headers,
  nowMs: number,
): number | null => {
  const resetAfterRaw = getHeaderValue(headers, [
    'x-ratelimit-reset-after',
    'ratelimit-reset-after',
  ]);
  if (resetAfterRaw !== null) {
    const resetAfter = Number(resetAfterRaw);
    if (Number.isFinite(resetAfter) && resetAfter > 0) {
      return clampDelaySeconds(resetAfter);
    }
  }

  const resetRaw = getHeaderValue(headers, ['x-ratelimit-reset', 'ratelimit-reset']);
  if (resetRaw === null) {
    return null;
  }

  const resetValue = Number(resetRaw);
  if (!Number.isFinite(resetValue) || resetValue <= 0) {
    return null;
  }

  if (resetValue > 1_000_000_000_000) {
    return clampDelaySeconds((resetValue - nowMs) / 1000);
  }

  if (resetValue > 1_000_000_000) {
    return clampDelaySeconds((resetValue * 1000 - nowMs) / 1000);
  }

  return clampDelaySeconds(resetValue);
};

/**
 * Parses `x-ratelimit-remaining` or `ratelimit-remaining` into a non-negative integer count,
 * treating identical repeats as one value. Missing or invalid values return null.
 */
export const parseRateLimitRemaining = (headers: Headers.Headers): number | null => {
  const raw = getHeaderValue(headers, ['x-ratelimit-remaining', 'ratelimit-remaining']);
  if (raw === null) {
    return null;
  }

  const parsed = Number(REPEATED_INTEGER_HEADER_RE.exec(raw)?.[1] ?? raw);
  if (!Number.isInteger(parsed) || parsed < 0) {
    return null;
  }

  return parsed;
};

/**
 * Extracts the `ETag` response header value when present.
 */
export const extractEtag = (headers: Headers.Headers): string | null =>
  getHeaderValue(headers, ['etag']);

/**
 * Extracts the `Last-Modified` response header value when present.
 */
export const extractLastModified = (headers: Headers.Headers): string | null =>
  getHeaderValue(headers, ['last-modified']);

/**
 * Detects whether a 403 response is a page a CDN, WAF or anti-bot service generated to block or
 * challenge the client: one of `EDGE_BLOCK_HEADERS` is set, or the body is HTML (by content type or
 * by its first tag) and carries one of the vendor markers in `HTML_EDGE_BLOCK_RE`. An ordinary `403
 * Forbidden` page from the origin is not a block.
 */
export const isHtmlEdgeBlock = (headers: Headers.Headers, body: string): boolean => {
  if (getHeaderValue(headers, EDGE_BLOCK_HEADERS) !== null) {
    return true;
  }

  const contentType = getHeaderValue(headers, ['content-type'])?.toLowerCase() ?? '';
  const trimmedBody = body.trimStart().toLowerCase();
  const looksLikeHtml =
    contentType.includes('text/html') ||
    trimmedBody.startsWith('<!doctype html') ||
    trimmedBody.startsWith('<html');
  if (!looksLikeHtml) {
    return false;
  }

  return HTML_EDGE_BLOCK_RE.test(body);
};

/**
 * Options controlling how HTTP 429 and 403 responses are inspected for rate limiting.
 */
export interface DetectRateLimitParams {
  /**
   * HTTP client response to inspect.
   */
  readonly response: HttpClientResponse.HttpClientResponse;

  /**
   * Logical upstream identifier for error attribution.
   */
  readonly upstream: string;

  /**
   * Whether HTTP 403 with `x-ratelimit-remaining: 0` should be classified as a rate limit.
   */
  readonly treatQuotaExhausted403AsRateLimit?: boolean | undefined;

  /**
   * Whether any HTTP 403 response should be classified as a rate limit.
   */
  readonly treat403AsRateLimit?: boolean | undefined;

  /**
   * Whether HTTP 403 HTML bodies should be scanned for CDN/WAF block signatures.
   */
  readonly detectHtmlEdgeBlocks?: boolean | undefined;
}

/**
 * Builds the rate limit for a 403 treated as an edge or WAF block, waiting `retryAfterSeconds`.
 */
const edgeBlockedError = (upstream: string, retryAfterSeconds: number): HttpRateLimitedError =>
  new HttpRateLimitedError({
    upstream,
    retryAfterSeconds,
    message: `${upstream} rate limited / edge blocked (HTTP 403)`,
  });

/**
 * Inspects an HTTP response and returns `Some(HttpRateLimitedError)` when it is rate-limited or
 * edge-blocked, `None` otherwise (any status but 429 and 403 is `None` without reading anything).
 * The edge-block check runs only when `detectHtmlEdgeBlocks` is `true`. It reads at most the first
 * 64 KiB of a 403 body under a 2 second budget, cancels the rest, and keeps what it read for the
 * status error's snippet. A body that stalls past the budget leaves the 403 a plain status error.
 */
export const detectRateLimitError = Effect.fnUntraced(function* (
  params: DetectRateLimitParams,
): Effect.fn.Return<Option.Option<HttpRateLimitedError>> {
  const {
    response,
    upstream,
    treatQuotaExhausted403AsRateLimit,
    treat403AsRateLimit,
    detectHtmlEdgeBlocks,
  } = params;
  if (response.status !== 429 && response.status !== 403) {
    return Option.none();
  }

  const nowMs = yield* Clock.currentTimeMillis;
  const retryAfterFromHeaders = parseRetryAfterSeconds(response.headers, nowMs);
  const retryAfterSeconds =
    retryAfterFromHeaders ?? parseRateLimitResetSeconds(response.headers, nowMs);
  if (response.status === 429) {
    return Option.some(
      new HttpRateLimitedError({
        upstream,
        retryAfterSeconds,
        message: `${upstream} rate limited (HTTP 429)`,
      }),
    );
  }

  const remaining = parseRateLimitRemaining(response.headers);
  if (treatQuotaExhausted403AsRateLimit === true && remaining === 0) {
    return Option.some(
      new HttpRateLimitedError({
        upstream,
        retryAfterSeconds,
        message: `${upstream} rate limited (HTTP 403)`,
      }),
    );
  }

  const edgeRetryAfterSeconds = retryAfterFromHeaders ?? DEFAULT_EDGE_403_RETRY_AFTER_SECONDS;
  if (treat403AsRateLimit === true) {
    return Option.some(edgeBlockedError(upstream, edgeRetryAfterSeconds));
  }

  if (detectHtmlEdgeBlocks !== true) {
    return Option.none();
  }

  const prefix = yield* readSharedBodyPrefix({ response, maxBytes: EDGE_BLOCK_SNIFF_BYTES });
  if (isHtmlEdgeBlock(response.headers, prefix.text)) {
    return Option.some(edgeBlockedError(upstream, edgeRetryAfterSeconds));
  }

  return Option.none();
});
