describe('detectRateLimitError', () => {
  it('returns Some rate-limit error for HTTP 429', async () => {
    const detected = await Effect.runPromise(
      detectRateLimitError({
        response: makeClientResponse(
          new Response(null, { status: 429, headers: { 'retry-after': '7' } }),
        ),
        upstream: 'test:detect',
      }),
    );
    expect(Option.getOrNull(detected)).toMatchObject({
      _tag: 'HttpRateLimitedError',
      upstream: 'test:detect',
      retryAfterSeconds: 7,
    });
  });

  it('returns None for a response that is not rate limited', async () => {
    const detected = await Effect.runPromise(
      Effect.forEach([200, 403], (status) =>
        detectRateLimitError({
          response: makeClientResponse(new Response(null, { status })),
          upstream: 'test:detect',
        }),
      ),
    );
    expect(detected.map(Option.isNone)).toEqual([true, true]);
  });
});
