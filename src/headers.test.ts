describe('parseRetryAfterSeconds', () => {
  it('reads identical repeated Retry-After values joined by Web Headers', () => {
    const headers = new globalThis.Headers([
      ['retry-after', '30'],
      ['retry-after', '30'],
    ]);
    expect(parseRetryAfterSeconds(Headers.fromInput(headers), 0)).toBe(30);
  });

  it('reads delta seconds and an HTTP-date', () => {
    const nowMs = Date.UTC(2026, 0, 15, 12, 0, 0);
    expect(parseRetryAfterSeconds(Headers.fromInput({ 'retry-after': '12' }), nowMs)).toBe(12);

    const futureDate = new Date(nowMs + 25_000).toUTCString();
    expect(parseRetryAfterSeconds(Headers.fromInput({ 'retry-after': futureDate }), nowMs)).toBe(
      25,
    );
  });

  it('cuts a delay too large for a finite millisecond count to the maximum', () => {
    const headers = Headers.fromInput({ 'retry-after': '9'.repeat(400) });
    const seconds = parseRetryAfterSeconds(headers, Date.now());
    expect(seconds).toBe(MAX_RATE_LIMIT_DELAY_SECONDS);
    expect(Number.isFinite(seconds)).toBe(true);
  });

  it('fails a 429 with a huge Retry-After as a typed rate limit, not a defect', async () => {
    const client = makeMockHttpClient(() =>
      Effect.succeed(
        new Response('slow down', { status: 429, headers: { 'retry-after': '9'.repeat(400) } }),
      ),
    );
    const exit = await Effect.runPromiseExit(
      executeTextRequest({
        client,
        request: HttpClientRequest.get('https://api.example.com/item'),
        upstream: 'test:huge-retry-after',
        retry: { maxRetries: 0 },
      }),
    );
    expect(squashExitFailure(exit)).toMatchObject({
      _tag: 'HttpRateLimitedError',
      retryAfterSeconds: MAX_RATE_LIMIT_DELAY_SECONDS,
    });
  });
});

describe('parseRateLimitResetSeconds', () => {
  it('reads an epoch-second reset header', () => {
    const nowMs = Date.UTC(2026, 0, 15, 12, 0, 0);
    const epochSec = Math.floor((nowMs + 42_000) / 1000);
    expect(
      parseRateLimitResetSeconds(
        Headers.fromInput({ 'x-ratelimit-reset': String(epochSec) }),
        nowMs,
      ),
    ).toBe(42);
  });

  it('cuts huge reset values to the maximum', () => {
    const nowMs = Date.UTC(2026, 0, 15, 12, 0, 0);
    for (const headers of [
      { 'x-ratelimit-reset-after': '1e308' },
      { 'x-ratelimit-reset': '1e308' },
      { 'x-ratelimit-reset': '1e20' },
    ]) {
      expect(parseRateLimitResetSeconds(Headers.fromInput(headers), nowMs)).toBe(
        MAX_RATE_LIMIT_DELAY_SECONDS,
      );
    }
  });
});

describe('parseRateLimitRemaining', () => {
  it('reads identical repeated quota counts joined by Web Headers', () => {
    const headers = new globalThis.Headers([
      ['x-ratelimit-remaining', '0'],
      ['x-ratelimit-remaining', '0'],
    ]);
    expect(parseRateLimitRemaining(Headers.fromInput(headers))).toBe(0);
  });

  it('rejects a fractional remaining count', () => {
    expect(parseRateLimitRemaining(Headers.fromInput({ 'x-ratelimit-remaining': '1.5' }))).toBe(
      null,
    );
    expect(parseRateLimitRemaining(Headers.fromInput({ 'x-ratelimit-remaining': '0' }))).toBe(0);
  });
});

describe('isHtmlEdgeBlock', () => {
  const htmlHeaders = Headers.fromInput({ 'content-type': 'text/html' });

  it('matches an HTML challenge and ignores a JSON 403 body', () => {
    expect(
      isHtmlEdgeBlock(htmlHeaders, '<html><title>Attention Required! | Cloudflare</title></html>'),
    ).toBe(true);
    expect(
      isHtmlEdgeBlock(Headers.fromInput({ 'content-type': 'application/json' }), '{"error":"no"}'),
    ).toBe(false);
  });

  it.each([
    '<html><head><title>Just a moment...</title></head><body><div id="cf-chl-widget"></div></body></html>',
    "<html><title>Access Denied</title><body>You don't have permission. Reference #18.6f1d2e17.1700000000.1a2b3c</body></html>",
    '<html><body><div class="g-recaptcha" data-sitekey="x"></div></body></html>',
    '<html><body><H1>403 ERROR</H1>Request blocked. Generated by cloudfront (CloudFront)</body></html>',
  ])('matches a vendor block page: %s', (body) => {
    expect(isHtmlEdgeBlock(htmlHeaders, body)).toBe(true);
  });

  it('does not treat an ordinary 403 Forbidden page as an edge block', () => {
    expect(
      isHtmlEdgeBlock(
        htmlHeaders,
        '<html><head><title>403 Forbidden</title></head><body><h1>Forbidden</h1>You do not have permission to access this resource. Access denied.<hr>nginx</body></html>',
      ),
    ).toBe(false);
  });

  it('matches a block the CDN announces in a header, whatever the body', () => {
    expect(isHtmlEdgeBlock(Headers.fromInput({ 'cf-mitigated': 'challenge' }), '')).toBe(true);
  });
});

describe('403 edge-block sniff', () => {
  it('reads only the start of a 10 MiB HTML block page', async () => {
    const { stream, tracker } = makeTrackedStream({
      totalBytes: 10 * 1024 * 1024,
      chunkBytes: 16 * 1024,
      prefix: '<!doctype html><html><title>Attention Required! | Cloudflare</title>',
    });
    const client = makeMockHttpClient(() =>
      Effect.succeed(
        new Response(stream, { status: 403, headers: { 'content-type': 'text/html' } }),
      ),
    );
    const exit = await Effect.runPromiseExit(
      executeTextRequest({
        client,
        request: HttpClientRequest.get('https://www.example.com/page'),
        upstream: 'test:edge',
        detectHtmlEdgeBlocks: true,
        retry: { maxRetries: 0 },
      }),
    );
    expect(squashExitFailure(exit)).toMatchObject({ _tag: 'HttpRateLimitedError' });
    expect(tracker.pulledBytes).toBeLessThanOrEqual(128 * 1024);
    expect(tracker.cancelled).toBe(true);
  });

  it('fails a 403 that is not a block page with the plain status error', async () => {
    const client = makeMockHttpClient(() =>
      Effect.succeed(
        new Response('<html><title>Members only</title></html>', {
          status: 403,
          headers: { 'content-type': 'text/html' },
        }),
      ),
    );
    const exit = await Effect.runPromiseExit(
      executeTextRequest({
        client,
        request: HttpClientRequest.get('https://www.example.com/page'),
        upstream: 'test:edge-miss',
        detectHtmlEdgeBlocks: true,
      }),
    );
    expect(squashExitFailure(exit)).toMatchObject({
      _tag: 'HttpRequestError',
      status: 403,
      message: 'test:edge-miss responded with HTTP 403',
      bodySnippet: 'Members only',
    });
    expect(exitOutcome(exit)).toBe('client_error');
  });

  it('keeps the snippet of a JSON 403 that the sniff already read', async () => {
    const client = makeMockHttpClient(() =>
      Effect.succeed(
        new Response(JSON.stringify({ message: 'Resource not accessible by integration' }), {
          status: 403,
          headers: { 'content-type': 'application/json' },
        }),
      ),
    );
    const exit = await Effect.runPromiseExit(
      executeTextRequest({
        client,
        request: HttpClientRequest.get('https://api.example.com/repo'),
        upstream: 'test:edge-json',
        detectHtmlEdgeBlocks: true,
      }),
    );
    expect(squashExitFailure(exit)).toMatchObject({
      message: 'test:edge-json responded with HTTP 403',
      bodySnippet: '{"message":"Resource not accessible by integration"}',
    });
  });

  it('keeps a 403 whose body stalls a plain status error within the sniff budget', async () => {
    const { stream, tracker } = makeTrackedStream({ totalBytes: 8, chunkBytes: 8, stall: true });
    const client = makeMockHttpClient(() =>
      Effect.succeed(
        new Response(stream, { status: 403, headers: { 'content-type': 'text/html' } }),
      ),
    );
    // The 10 second attempt timeout would also end in a plain 403, so the test checks the request
    // ends at the 2 second sniff budget and not before or after it.
    const result = await Effect.runPromise(
      Effect.gen(function* () {
        const request = yield* forkUntilSuspended(
          executeTextRequest({
            client,
            request: HttpClientRequest.get('https://www.example.com/page'),
            upstream: 'test:edge-stall',
            detectHtmlEdgeBlocks: true,
            attemptTimeout: '10 seconds',
            retry: { maxRetries: 0 },
          }),
        );
        yield* TestClock.adjust('1999 millis');
        const doneBeforeBudget = yield* isFiberDone(request);
        yield* TestClock.adjust('1 millis');
        const doneAtBudget = yield* isFiberDone(request);
        return { doneBeforeBudget, doneAtBudget, exit: yield* Fiber.await(request) };
      }).pipe(Effect.provide(TestClock.layer())),
    );
    const { exit } = result;
    expect(result.doneBeforeBudget).toBe(false);
    expect(result.doneAtBudget).toBe(true);
    expect(squashExitFailure(exit)).toMatchObject({
      _tag: 'HttpRequestError',
      status: 403,
      message: 'test:edge-stall responded with HTTP 403',
    });
    expect(exitOutcome(exit)).toBe('client_error');
    expect(tracker.cancelled).toBe(true);
  });
});

